CHINESE_NUMBERS = ("一", "二", "三", "四", "五", "六", "七", "八", "九", "十", "十一", "十二")


def render_policy(spec: dict[str, Any]) -> str:
    lines = [
        f"# {spec['title']}", "", "## 第一章 可判断业务规则", "",
    ]
    for index, item in enumerate(spec["rules"], start=1):
        number = CHINESE_NUMBERS[index - 1]
        lines.extend([
            f"第{number}条 【{item['title']}】{item['body']}",
            f"知识库标识：{LIBRARY_NAME}。",
            f"使用声明：{DISCLAIMER}",
            f"制度名称：{spec['title']}。",
            f"制度编号：{spec['code']}。",
            f"生效日期：{spec['effective_date']}。",
            f"适用对象：{spec['audience']}。",
            f"适用部门：{spec['departments']}。",
            f"资格条件：{item['eligibility']}。",
            f"排除条件：{item['exclusion']}。",
            f"时间限制：{item['deadline']}。",
            f"次数 / 天数 / 金额上限：{item['limit']}。",
            f"所需材料：{item['materials']}。",
            f"办理步骤：{item['steps']}。",
            f"提交对象：{item['submit_to']}。",
            f"审批角色：{item['approver']}。",
            f"HR处理角色：{item['hr_role']}。",
            f"对应条款正文：{item['body']}。",
            "",
        ])
    return "\n".join(lines).strip() + "\n"


